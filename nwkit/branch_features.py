"""Branch feature tables with explicit, caller-preserving clade-rank IDs."""

import math
import os
import sys
from collections import Counter
from typing import Any

import ete4
import numpy
import pandas

from nwkit.clade_index import LcaIndex
from nwkit.rooting_state import extract_rooting_token
from nwkit.taxonomic_labels import extract_species_label, scientific_name_from_label


def iter_leaves(tree):
    return tree.leaves()


def get_leaf_names_compat(tree):
    return list(tree.leaf_names())


def _ensure_branch_ids(tree):
    nodes = list(tree.traverse())
    if not nodes:
        return tree
    leaf_names = sorted(leaf.name for leaf in iter_leaves(tree))
    if not leaf_names:
        for rank, node in enumerate(nodes):
            _set_node_prop(node, "branch_id", rank)
        return tree
    if len(set(leaf_names)) == len(leaf_names):
        keys = _unique_clade_rank_keys(tree, leaf_names)
    else:
        keys = _clade_rank_masks(tree, leaf_names)
    # Stable sorting keeps the original level order for identical clades.
    # Once sorted, reuse the key mapping for the assigned ranks.
    for rank, node in enumerate(sorted(nodes, key=keys.__getitem__)):
        keys[node] = rank
    for node in nodes:
        _set_node_prop(node, "branch_id", keys[node])
    return tree


def _unique_clade_rank_keys(tree, leaf_names):
    # The highest differing bit orders disjoint clades. Clades sharing
    # their highest bit are nested, so size orders them.
    tip_ranks = {name: rank for rank, name in enumerate(leaf_names)}
    keys = {}
    for node in tree.traverse(strategy="postorder"):
        if node_is_leaf(node):
            keys[node] = (tip_ranks[node.name], 1)
        else:
            largest_rank, tip_count = -1, 0
            for child in node.get_children():
                child_rank, child_count = keys[child]
                if child_rank > largest_rank:
                    largest_rank = child_rank
                tip_count += child_count
            keys[node] = (largest_rank, tip_count)
    return keys


def _clade_rank_masks(tree, leaf_names):
    # With duplicate names, disjoint subtrees can share some of their bits.
    leaf_branch_ids = {name: 1 << i for i, name in enumerate(leaf_names)}
    node_label_sum = {}
    for node in tree.traverse(strategy="postorder"):
        if node_is_leaf(node):
            node_label_sum[node] = leaf_branch_ids[node.name]
        else:
            node_mask = 0
            for child in node.get_children():
                node_mask |= node_label_sum[child]
            node_label_sum[node] = node_mask
    return node_label_sum


def _get_node_label(node):
    label = _get_node_prop(node, "branch_id", None)
    if label is None:
        raise AttributeError("Node branch_id is unavailable.")
    try:
        return int(label)
    except (TypeError, ValueError):
        return label


def _get_node_prop(node, key, default=None):
    if hasattr(node, key):
        return getattr(node, key)
    if hasattr(node, "props"):
        return node.props.get(key, default)
    return default


def _set_node_prop(node, key, value):
    if hasattr(node, "add_prop"):
        node.add_prop(key, value)
        return
    try:
        setattr(node, key, value)
        return
    except (AttributeError, TypeError):
        pass
    if hasattr(node, "props"):
        node.props[key] = value


def clone_tree_for_species_mapping(tree):
    """Clone the topology fields used by ``node_gene2species`` iteratively.

    ETE nodes keep parent and child references, so ``copy.deepcopy`` can
    exhaust Python's recursion limit on valid, highly unbalanced gene trees.
    Species mapping needs only topology, names, branch lengths, and support;
    branch IDs are deterministically regenerated by the caller.
    """

    clone = tree.__class__()
    pending = [(tree, clone)]
    while pending:
        source, target = pending.pop()
        target.name = source.name
        target.dist = source.dist
        source_support = getattr(source, "support", None)
        if source_support is not None:
            target.support = source_support
        for source_child in source.get_children():
            target_child = target.add_child()
            pending.append((source_child, target_child))
    return clone


def node_is_leaf(node):
    return bool(node.is_leaf)


def node_is_root(node):
    return bool(node.is_root)


def _tree_tip_names(tree):
    """Return the validated leaf labels without constructing descendant sets."""
    leaf_names = [
        str(leaf.name) if leaf.name is not None else "" for leaf in iter_leaves(tree)
    ]
    if any(not name for name in leaf_names):
        raise ValueError("Tree contains an empty leaf label.")
    duplicate_names = sorted(
        name for name, count in Counter(leaf_names).items() if count > 1
    )
    if duplicate_names:
        raise ValueError(f"Tree contains duplicate leaf labels: {duplicate_names[:5]}")
    return frozenset(leaf_names)


def _internal_split_masks(tree, tip_masks, full_mask):
    """Index splits in one shared tip catalog, retaining traversal order."""

    descendants = {}
    for node in tree.traverse(strategy="postorder"):
        if node_is_leaf(node):
            descendants[node] = tip_masks[str(node.name)]
        else:
            mask = 0
            for child in node.get_children():
                mask |= descendants[child]
            descendants[node] = mask

    tip_count = len(tip_masks)
    nodes_by_split: dict[int, list[Any]] = {}
    for node in tree.traverse():
        if node_is_root(node) or node_is_leaf(node):
            continue
        mask = descendants[node]
        size = mask.bit_count()
        if min(size, tip_count - size) < 2:
            continue
        # Equal-sized complements are disjoint; the side containing the
        # lexicographically first tip has the smaller sorted tuple.
        if 2 * size > tip_count or (2 * size == tip_count and not mask & 1):
            mask = full_mask ^ mask
        nodes_by_split.setdefault(mask, []).append(node)
    return nodes_by_split


def _split_mask_preview(masks, ordered_tips):
    """Decode only diagnostics, preserving the existing sorted tuple previews."""

    splits = []
    for mask in masks:
        names = []
        while mask:
            bit = mask & -mask
            names.append(ordered_tips[bit.bit_length() - 1])
            mask ^= bit
        splits.append(tuple(names))
    return sorted(splits)[:2]


def new_tree(newick_or_path, format=1, quoted_node_names=False):
    _ = quoted_node_names
    if isinstance(newick_or_path, str) and os.path.exists(newick_or_path):
        with open(newick_or_path, "r", encoding="utf-8") as handle:
            newick_or_path = handle.read().strip()
    if isinstance(newick_or_path, str):
        # Rooting declarations are document metadata, not ETE node NHX.
        # NWKIT's reader removes only leading tokens; labels and NHX stay intact.
        newick_or_path, _ = extract_rooting_token(newick_or_path)
    return ete4.PhyloTree(newick_or_path, parser=format)


def nwk2table(tree, attr="", age=False, parent=False, sister=False):
    tree_format = 0 if attr == "support" else 1
    if isinstance(tree, str):
        tree = new_tree(tree, format=tree_format)
    tree = ensure_branch_ids(tree)
    nodes = list(tree.traverse())
    age_by_label = {}
    if (attr == "dist") and age:
        for node in tree.traverse(strategy="postorder"):
            nlabel = get_node_label(node)
            if node_is_leaf(node):
                age_by_label[nlabel] = 0.0
            else:
                first_child = node.get_children()[0]
                age_by_label[nlabel] = (
                    age_by_label[get_node_label(first_child)] + first_child.dist
                )
    rows = []
    for node in nodes:
        nlabel = get_node_label(node)
        if attr == "":
            attr_value = numpy.nan
        else:
            attr_value = get_node_prop(node, attr, numpy.nan)
        row = {
            "branch_id": nlabel,
            attr: attr_value,
        }
        if (attr == "dist") and age:
            row["age"] = age_by_label.get(nlabel, numpy.nan)
        if parent:
            if node_is_root(node):
                row["parent"] = -999
            else:
                row["parent"] = get_node_label(node.up)
        if sister:
            if node_is_root(node):
                row["sister"] = -999
            else:
                sisters = node.get_sisters()
                row["sister"] = (
                    get_node_label(sisters[0]) if len(sisters) == 1 else -999
                )
        rows.append(row)
    df = pandas.DataFrame.from_records(rows)
    return df.sort_values(by="branch_id").reset_index(drop=True)


def node_gene2species(gene_tree, species_tree, is_ultrametric=False):
    gene_tree2 = clone_tree_for_species_mapping(gene_tree)
    gene_tree2 = ensure_branch_ids(gene_tree2)
    for leaf in iter_leaves(gene_tree2):
        species_label = extract_species_label(leaf.name)
        if species_label != "":
            leaf.name = species_label
    tip_set_diff = set(get_leaf_names_compat(gene_tree2)) - set(
        get_leaf_names_compat(species_tree)
    )
    if tip_set_diff:
        sys.stderr.write(
            f"Warning. A total of {len(tip_set_diff)} species are missing in the species tree: {str(tip_set_diff)}\n"
        )
    cn = ["branch_id", "spnode_coverage"]
    if is_ultrametric:
        cn.append("spnode_age")
    species_nodes = list(species_tree.traverse(strategy="postorder"))
    species_names = {sn: (sn.name or "").replace("'", "") for sn in species_nodes}
    species_leaf_node = {leaf.name: leaf for leaf in iter_leaves(species_tree)}
    species_depth: dict[Any, int] = {}
    for sn in species_tree.traverse(strategy="preorder"):
        species_depth[sn] = 0 if node_is_root(sn) else (species_depth[sn.up] + 1)
    if is_ultrametric:
        species_age = {}
        for sn in species_nodes:
            if node_is_leaf(sn):
                species_age[sn] = 0.0
            else:
                first_child = sn.get_children()[0]
                species_age[sn] = species_age[first_child] + first_child.dist
        species_up_age = {}
        for sn in species_nodes:
            if node_is_root(sn):
                species_up_age[sn] = numpy.inf
            else:
                species_up_age[sn] = species_age[sn.up]
    species_lca = LcaIndex(species_tree)
    pair_lca = species_lca.common_ancestor

    gene_nodes = list(gene_tree2.traverse(strategy="postorder"))
    gene_coverage = {}
    gene_has_missing_species = {}
    if is_ultrametric:
        gene_age = {}
    for gn in gene_nodes:
        if node_is_leaf(gn):
            covered_species_node = species_leaf_node.get(gn.name)
            gene_coverage[gn] = covered_species_node
            gene_has_missing_species[gn] = covered_species_node is None
            if is_ultrametric:
                gene_age[gn] = 0.0
            continue
        children = gn.get_children()
        if is_ultrametric:
            first_child = children[0]
            gene_age[gn] = gene_age[first_child] + first_child.dist
        has_missing_species = any(gene_has_missing_species[child] for child in children)
        gene_has_missing_species[gn] = has_missing_species
        if has_missing_species:
            gene_coverage[gn] = None
            continue
        covered_species_node = gene_coverage[children[0]]
        for child in children[1:]:
            covered_species_node = pair_lca(covered_species_node, gene_coverage[child])
        gene_coverage[gn] = covered_species_node

    rows = []
    for gn in gene_nodes:
        coverage_node = gene_coverage[gn]
        row = {
            "branch_id": get_node_label(gn),
            "spnode_coverage": ""
            if coverage_node is None
            else species_names[coverage_node],
        }
        if is_ultrametric:
            row["spnode_age"] = ""
            if coverage_node is not None:
                gn_age = gene_age[gn]
                current_species_node = coverage_node
                while current_species_node is not None:
                    if (gn_age >= species_age[current_species_node]) and (
                        gn_age < species_up_age[current_species_node]
                    ):
                        row["spnode_age"] = species_names[current_species_node]
                        break
                    current_species_node = current_species_node.up
        rows.append(row)
    return pandas.DataFrame(rows, columns=cn)


def get_misc_node_statistics(tree_file, tax_annot=False):
    tree = new_tree(tree_file, format=1)
    tree = ensure_branch_ids(tree)
    cn1 = [
        "branch_id",
        "taxon",
        "taxid",
        "num_sp",
        "num_leaf",
        "so_event",
        "dup_conf_score",
    ]
    cn2 = ["parent", "sister", "child1", "child2", "so_event_parent"]
    cn = cn1 + cn2
    nodes = list(tree.traverse())
    if tax_annot:
        raise NotImplementedError(
            "tax_annot=True is unsupported in the ETE4 compatibility path."
        )
    sci_name_by_node = {}
    taxid_by_node = {}
    for node in nodes:
        taxid_by_node[node] = -999
        if node_is_leaf(node):
            sci_name_by_node[node] = scientific_name_from_label(node.name)
        else:
            sci_name_by_node[node] = ""
    species_index: dict[str, int] = {}
    species_mask_by_node = {}
    num_leaf_by_node = {}
    dup_conf_score_by_node = {}
    for node in tree.traverse(strategy="postorder"):
        if node_is_leaf(node):
            species_id = species_index.setdefault(
                sci_name_by_node[node], len(species_index)
            )
            species_mask_by_node[node] = 1 << species_id
            num_leaf_by_node[node] = 1
            dup_conf_score_by_node[node] = 0.0
            continue
        children = node.get_children()
        species_mask = 0
        num_leaf = 0
        for child in children:
            species_mask |= species_mask_by_node[child]
            num_leaf += num_leaf_by_node[child]
        species_mask_by_node[node] = species_mask
        num_leaf_by_node[node] = num_leaf
        if len(children) >= 2:
            child1_mask = species_mask_by_node[children[0]]
            child2_mask = species_mask_by_node[children[1]]
            union_mask = child1_mask | child2_mask
            union_count = union_mask.bit_count()
            if union_count == 0:
                dup_conf_score_by_node[node] = 0.0
            else:
                dup_conf_score_by_node[node] = (
                    child1_mask & child2_mask
                ).bit_count() / union_count
        else:
            dup_conf_score_by_node[node] = 0.0
    rows = []
    for node in nodes:
        label = get_node_label(node)
        children = node.get_children()
        if not node_is_root(node):
            parent = get_node_label(node.up)
            sisters = node.get_sisters()
            # A singular sister ID is meaningful only for binary parents.
            sister = get_node_label(sisters[0]) if len(sisters) == 1 else -999
        else:
            parent = -999
            sister = -999
        child1 = get_node_label(children[0]) if len(children) >= 1 else -999
        child2 = get_node_label(children[1]) if len(children) >= 2 else -999
        node_dup_conf_score = dup_conf_score_by_node.get(node, 0.0)
        if node_is_leaf(node):
            so_event = "L"
        else:
            so_event = "D" if node_dup_conf_score > 0 else "S"
        so_event_parent = "S"
        if (node.up is not None) and (dup_conf_score_by_node.get(node.up, 0.0) > 0):
            so_event_parent = "D"
        rows.append(
            {
                "branch_id": label,
                "taxon": str(sci_name_by_node[node]),
                "taxid": taxid_by_node[node],
                "num_sp": species_mask_by_node[node].bit_count(),
                "num_leaf": num_leaf_by_node[node],
                "so_event": so_event,
                "dup_conf_score": node_dup_conf_score,
                "parent": parent,
                "sister": sister,
                "child1": child1,
                "child2": child2,
                "so_event_parent": so_event_parent,
            }
        )
    return pandas.DataFrame(rows, columns=cn)


def map_internal_support_by_split(
    rooted_tree,
    support_tree,
    support_max=None,
    require_support=False,
):
    """Map edge support by canonical unrooted bipartition.

    A rooted binary representation contains the root split twice (once on each
    root-child edge), whereas an unrooted tree contains it once.  Canonical
    split keys make the mapping independent of root placement and avoid
    silently assigning values by incompatible rooted clades.
    """

    rooted_tips = _tree_tip_names(rooted_tree)
    support_tips = _tree_tip_names(support_tree)
    if rooted_tips != support_tips:
        only_rooted = sorted(rooted_tips.difference(support_tips))
        only_support = sorted(support_tips.difference(rooted_tips))
        raise ValueError(
            "Support and rooted trees have different leaf sets: "
            f"only_in_rooted={only_rooted[:5]}, only_in_support={only_support[:5]}"
        )

    ordered_tips = sorted(rooted_tips)
    tip_masks = {name: 1 << index for index, name in enumerate(ordered_tips)}
    full_mask = (1 << len(ordered_tips)) - 1
    rooted_nodes = _internal_split_masks(rooted_tree, tip_masks, full_mask)
    support_nodes = _internal_split_masks(support_tree, tip_masks, full_mask)
    rooted_splits = set(rooted_nodes)
    support_splits = set(support_nodes)
    if rooted_splits != support_splits:
        only_rooted_splits = rooted_splits.difference(support_splits)
        only_support_splits = support_splits.difference(rooted_splits)
        raise ValueError(
            "Support and rooted trees have incompatible unrooted topologies: "
            f"only_in_rooted={len(only_rooted_splits)}, only_in_support={len(only_support_splits)}; "
            f"rooted_preview={_split_mask_preview(only_rooted_splits, ordered_tips)}, "
            f"support_preview={_split_mask_preview(only_support_splits, ordered_tips)}"
        )

    support_by_split = {}
    for split, nodes in support_nodes.items():
        values = []
        for node in nodes:
            value = getattr(node, "support", None)
            if value is None and hasattr(node, "props"):
                value = node.props.get("support")
            if value is None:
                continue
            value = float(value)
            if not math.isfinite(value) or value < 0:
                raise ValueError(f"Tree contains an invalid support value: {value!r}")
            if support_max is not None and value > support_max + 1e-8:
                raise ValueError(
                    f"Tree support value {value!r} exceeds the expected maximum {support_max}."
                )
            values.append(value)
        if not values:
            continue
        if max(values) - min(values) > 1e-8:
            raise ValueError(
                f"The two rooted representations of one unrooted split carry different support values: {values}"
            )
        support_by_split[split] = values[0]

    # A partially labelled support tree is more dangerous than a completely
    # unlabelled tree (the latter is expected for families with <4 sequences).
    if support_by_split and set(support_by_split) != support_splits:
        missing = support_splits.difference(support_by_split)
        raise ValueError(
            "Support tree labels only a subset of its internal splits: "
            f"supported={len(support_by_split)}, total={len(support_splits)}, "
            f"missing_preview={_split_mask_preview(missing, ordered_tips)}"
        )
    if require_support and support_splits and not support_by_split:
        raise ValueError(
            f"Support tree has internal splits but no explicit support labels: total={len(support_splits)}"
        )

    branch_support = {}
    for split, nodes in rooted_nodes.items():
        if split not in support_by_split:
            continue
        for node in nodes:
            branch_id = node.props.get("branch_id") if hasattr(node, "props") else None
            if branch_id is None:
                branch_id = getattr(node, "branch_id", None)
            if branch_id is None:
                raise ValueError(
                    "Rooted tree node is missing branch_id during support mapping."
                )
            branch_support[int(branch_id)] = support_by_split[split]

    if branch_support:
        from nwkit.transfer import transfer_properties
        from nwkit.util import copy_tree_iteratively

        normalized_source = copy_tree_iteratively(support_tree)
        for split, nodes in _internal_split_masks(
            normalized_source, tip_masks, full_mask
        ).items():
            if split in support_by_split:
                for node in nodes:
                    node.support = support_by_split[split]
        target = copy_tree_iteratively(rooted_tree)
        transfer_properties(
            target,
            normalized_source,
            [("support", "support")],
            target_class="intnode",
            match_basis="split",
            align_roots=False,
            allow_target_reroot=False,
            exclude_root=True,
            root_edge_policies={"support": "equal-only"},
            collect_report=False,
            equal_value_ambiguity=True,
        )
        mapped_support = {
            int(node.props["branch_id"]): float(node.support)
            for node in target.traverse()
            if node.props.get("branch_id") in branch_support
        }

    if branch_support:
        branch_support = {key: mapped_support[key] for key in branch_support}

    values = list(support_by_split.values())
    diagnostics = {
        "internal_split_count": len(rooted_splits),
        "supported_split_count": len(support_by_split),
        "support_min": min(values) if values else None,
        "support_max": max(values) if values else None,
        "all_support_100": bool(values)
        and all(abs(value - 100.0) <= 1e-8 for value in values),
    }
    return branch_support, diagnostics


